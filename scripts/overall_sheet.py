"""Add a live "Overall" column (an Excel formula) to every team sheet of proa_scraped.xlsx.

The weights come from data/overall_model.json (fit_overall.py) and are written to a '_Overall_Model' sheet, so the column
recomputes whenever a rating or the position is edited. Re-run after refitting the model (fit_overall.py does this itself):

    python scripts/overall_sheet.py [workbook.xlsx]

The scraper calls add_overall() too, so a fresh scrape keeps the column.
"""
import sys
from pathlib import Path

import openpyxl
from openpyxl.styles import Font
from openpyxl.utils import get_column_letter as L

sys.path.insert(0, str(Path(__file__).resolve().parent))
from overall_data import default_extras  # noqa: E402
from overall_model import POS_NAMES, load_model  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
MODEL_SHEET = "_Overall_Model"
COLUMN = "Overall"


def _model_rows(model):
    """Per position: attribute weights, a constant (intercept plus the neutral record bytes) and the DunkFlag weight."""
    ex = model.get("extras")
    const_ex, dunk_w = 0.0, 0.0
    if ex:
        neutral = default_extras({"Dunk": 0})
        for name, w in zip(ex["names"], ex["weights"]):
            if name == "DunkFlag":
                dunk_w = w
            else:
                const_ex += w * neutral[name]
    for p in POS_NAMES:
        m = model["positions"][p]
        yield p, m["weights"], m["intercept"] + const_ex, dunk_w


def write_model_sheet(wb, model):
    if MODEL_SHEET in wb.sheetnames:
        del wb[MODEL_SHEET]
    ws = wb.create_sheet(MODEL_SHEET)
    attrs = model["attributes"]
    hw = model.get("height_weight", {}).get("coef_per_unit", [0.0, 0.0])
    ws.append(["Position", *attrs, "Intercept", "DunkFlag weight", "Height coef (per m)", "Weight coef (per kg)"])
    for p, weights, const, dunk_w in _model_rows(model):
        ws.append([p, *weights, const, dunk_w, hw[0], hw[1]])
    for c in ws[1]:
        c.font = Font(bold=True)
    notes = [
        "Overall = ROUND(intercept + sum(weight * rating) + DunkFlag weight * DunkFlag + height/weight terms), weights by Position.",
        "DunkFlag = 99 if Dunk >= 75, 50 if Dunk >= 60, else 0 (what build_roster writes to the record).",
        "The intercept already contains the neutral record bytes build_roster writes (B4F, B50, B55, ...).",
        f"Generated by scripts/overall_sheet.py from data/overall_model.json (LOO error {model.get('loo_rmse')}, n={model.get('n')}). Edit the model via fit_overall.py, not here.",
    ]
    for i, t in enumerate(notes):
        ws.cell(len(POS_NAMES) + 3 + i, 1, t)
    ws.column_dimensions["A"].width = 10
    for ci in range(2, len(attrs) + 6):
        ws.column_dimensions[L(ci)].width = 12
    return ws


def formula(r, col, attrs_span, n_attrs):
    """col: column letter by header name; attrs_span: (first, last) rating column letters."""
    first, last = attrs_span
    tbl = f"'{MODEL_SHEET}'!"
    k = len(POS_NAMES) + 1
    m = f"MATCH(${col['Position']}{r},{tbl}$A$2:$A${k},0)"
    c = lambda letter: f"INDEX({tbl}${letter}$2:${letter}${k},{m})"  # noqa: E731
    i0 = n_attrs + 2
    dunk = f"IF({col['Dunk']}{r}>=75,99,IF({col['Dunk']}{r}>=60,50,0))"
    return (f'=IF(ISNA({m}),"",ROUND(SUMPRODUCT({first}{r}:{last}{r},INDEX({tbl}$B$2:${L(n_attrs + 1)}${k},{m},0))'
            f"+{c(L(i0))}+{c(L(i0 + 1))}*{dunk}"
            f"+{c(L(i0 + 2))}*{col['Height']}{r}+{c(L(i0 + 3))}*{col['Weight']}{r},0))")


def add_overall(wb, model=None):
    """Add/refresh the Overall formula column on every sheet that has a 'ProA ID' column. Returns the number of rows."""
    model = model or load_model()
    if model is None:
        raise SystemExit("no data/overall_model.json - run fit_overall.py first")
    attrs = model["attributes"]
    n = 0
    for ws in list(wb):
        if ws.title == MODEL_SHEET:
            continue
        hdr = [c.value for c in ws[1]]
        if "ProA ID" not in hdr:
            continue
        col = {h: L(i + 1) for i, h in enumerate(hdr) if h and h != COLUMN}
        idx = [hdr.index(a) for a in attrs]
        if idx != list(range(idx[0], idx[0] + len(attrs))):
            raise SystemExit(f"{ws.title}: rating columns are not contiguous / in model order")
        out = hdr.index(COLUMN) + 1 if COLUMN in hdr else len(hdr) + 1
        ws.cell(1, out, COLUMN)
        span = (L(idx[0] + 1), L(idx[-1] + 1))
        for r in range(2, ws.max_row + 1):
            if ws.cell(r, hdr.index("Last Name") + 1).value:
                ws.cell(r, out, formula(r, col, span, len(attrs)))
                n += 1
        ws.column_dimensions[L(out)].width = 9
    write_model_sheet(wb, model)
    return n


def main():
    path = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "proa_scraped.xlsx"
    wb = openpyxl.load_workbook(path)
    n = add_overall(wb)
    wb.save(path)
    print(f"{path.name}: Overall formula written for {n} players; weights on sheet {MODEL_SHEET}")


if __name__ == "__main__":
    main()
